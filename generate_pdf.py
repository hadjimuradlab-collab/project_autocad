def build_specification(elements):
    from generate_specification import SPEC_DATA, CALC_ROOMS, LOOPS_INFO, CABLE_LOG

    # СПЕЦИФИКАЦИЯ
    elements.append(p("СПЕЦИФИКАЦИЯ ОБОРУДОВАНИЯ И МАТЕРИАЛОВ", H1))
    spec_table = [["№", "Наименование", "Тип, марка", "Ед.", "Кол.", "Примечание"]]
    for pos, name, mark, unit, qty, note in SPEC_DATA:
        spec_table.append([pos, name, mark, unit, str(qty), note])
    elements.append(make_table(spec_table,
                               col_widths=[0.9 * cm, 5.5 * cm, 3.2 * cm,
                                           1 * cm, 1.2 * cm, 4.2 * cm]))
    elements.append(PageBreak())

    # РАСЧЁТ ИП
    elements.append(p("РАСЧЁТ КОЛИЧЕСТВА ИЗВЕЩАТЕЛЕЙ ПО ПОМЕЩЕНИЯМ", H1))
    calc_table = [["Эт.", "№", "Помещение", "S, м²", "ИП 212", "ИП 101", "Обоснование"]]
    f1_212 = f2_212 = f1_101 = f2_101 = f1_s = f2_s = 0
    for fl, no, room, area, q212, q101, base in CALC_ROOMS:
        calc_table.append([fl, no, room, area, q212 or "—", q101 or "—", base])
        if fl == 1:
            f1_212 += q212; f1_101 += q101; f1_s += area
        else:
            f2_212 += q212; f2_101 += q101; f2_s += area
    calc_table.append([Paragraph("<b>Итого 1 эт.</b>", TABLE_CELL_C), "", "",
                       round(f1_s, 1), f1_212, f1_101, ""])
    calc_table.append([Paragraph("<b>Итого 2 эт.</b>", TABLE_CELL_C), "", "",
                       round(f2_s, 1), f2_212, f2_101, ""])
    calc_table.append([Paragraph("<b>ВСЕГО</b>", TABLE_CELL_C), "", "",
                       round(f1_s + f2_s, 1), f1_212 + f2_212, f1_101 + f2_101, ""])
    elements.append(make_table(calc_table,
                               col_widths=[0.9 * cm, 0.9 * cm, 3.6 * cm,
                                           1.4 * cm, 1.6 * cm, 1.6 * cm, 6 * cm]))
    elements.append(PageBreak())

    # ШЛЕЙФЫ
    elements.append(p("РАСПРЕДЕЛЕНИЕ УСТРОЙСТВ ПО ШЛЕЙФАМ ППКП ГРАНИТ-12", H1))
    loops_table = [["ШС", "Назначение", "Состав", "Устр.", "I, мА"]]
    for loop, purpose, content, qty, current in LOOPS_INFO:
        loops_table.append([f"ШС {loop}", purpose, content, qty, current])
    elements.append(make_table(loops_table,
                               col_widths=[1.2 * cm, 3.5 * cm, 8.6 * cm,
                                           1.4 * cm, 1.3 * cm]))
    elements.append(PageBreak())

    # КАБЕЛЬНЫЙ ЖУРНАЛ
    elements.append(p("КАБЕЛЬНЫЙ ЖУРНАЛ", H1))
    cable_table = [["№", "Участок", "Марка кабеля", "L, м", "Способ", "Прим."]]
    totals = {}
    for no, span, cab, length, way, note in CABLE_LOG:
        cable_table.append([no, span, cab, length, way, note])
        totals[cab] = totals.get(cab, 0) + length
    cable_table.append([Paragraph("<b>Итого с запасом 20%:</b>", TABLE_CELL),
                        "", "", "", "", ""])
    for cab, length in totals.items():
        cable_table.append(["", cab, "",
                            round(length * 1.20), "", ""])
    elements.append(make_table(cable_table,
                               col_widths=[0.8 * cm, 4.5 * cm, 3.5 * cm,
                                           1.2 * cm, 2.5 * cm, 3.5 * cm]))
    elements.append(PageBreak())


