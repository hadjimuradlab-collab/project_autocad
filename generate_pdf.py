def p(text, style=BODY):
    return Paragraph(text, style)


def bullet(text):
    return Paragraph(f"• {text}", BULLET)


def make_table(data, col_widths, header_rows=1):
    """Создаёт стандартизованную таблицу с шапкой и тонкими границами."""
    rows = []
    for r_idx, row in enumerate(data):
        new_row = []
        for c_idx, cell in enumerate(row):
            if isinstance(cell, Paragraph):
                new_row.append(cell)
            else:
                style = TABLE_HEADER if r_idx < header_rows else (
                    TABLE_CELL_C if c_idx == 0 else TABLE_CELL
                )
                new_row.append(Paragraph(str(cell), style))
        rows.append(new_row)

    t = Table(rows, colWidths=col_widths, repeatRows=header_rows)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, header_rows - 1), colors.HexColor("#D9E1F2")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    return t


