def build_pdf(output="project.pdf"):
    doc = SimpleDocTemplate(
        output, pagesize=A4,
        leftMargin=2.5 * cm, rightMargin=1.5 * cm,
        topMargin=1.5 * cm, bottomMargin=1.5 * cm,
        title="Проект АПС — административное здание",
        author="Claude Code",
    )
    elements = []
    build_title_page(elements)
    build_toc(elements)
    build_pz(elements)
    build_specification(elements)
    build_plans(elements)
    doc.build(elements, onFirstPage=_draw_page_decor, onLaterPages=_draw_page_decor)
    print(f"✓ Сохранено: {output}")


