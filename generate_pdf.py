def _draw_page_decor(canvas, doc):
    canvas.saveState()
    canvas.setFont("Body", 9)
    canvas.setFillColor(colors.grey)
    canvas.drawCentredString(A4[0] / 2, 1.0 * cm,
                              f"— {doc.page} —")
    canvas.drawRightString(A4[0] - 1.5 * cm, A4[1] - 0.8 * cm,
                            "АПС-АДМ-01")
    canvas.restoreState()


